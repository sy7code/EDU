import { describe, expect, it } from "vitest";
import { maskName, maskPii } from "./privacy";

describe("maskName", () => {
  it.each([
    ["", ""],
    ["김", "*"],
    ["이준", "이*"],
    ["김민수", "김*수"],
    ["남궁다온", "남**온"],
    ["  박하늘 ", "박*늘"],
  ])("%s → %s", (input, expected) => {
    expect(maskName(input)).toBe(expected);
  });
});

describe("maskPii", () => {
  it("전화번호 형식을 가린다", () => {
    expect(maskPii("010-1234-5678, 01012345678, 011 123 4567")).toBe("[연락처], [연락처], [연락처]");
  });

  it("이메일과 주민번호를 가린다", () => {
    expect(maskPii("a.b@test.com 050101-3123456")).toBe("[이메일] [주민번호]");
  });

  it("긴 이름을 먼저 치환해 부분 이름이 남지 않는다", () => {
    expect(maskPii("남궁다온과 다온", ["다온", "남궁다온"])).toBe("[이름]과 [이름]");
  });

  it("한 글자 이름은 치환하지 않아 일반 단어를 망가뜨리지 않는다", () => {
    expect(maskPii("김치 맛있다", ["김"])).toBe("김치 맛있다");
  });

  it("성을 뺀 이름(호칭 포함)도 가린다", () => {
    expect(maskPii("가온이한테 물어봤어", ["김가온"])).toBe("[이름]이한테 물어봤어");
  });

  it("점·공백 구분, +82, 유선 전화번호를 가린다", () => {
    expect(maskPii("010.1234.5678 / +82 10-1234-5678 / 02-123-4567 / 031 1234 5678")).toBe(
      "[연락처] / [연락처] / [연락처] / [연락처]",
    );
  });

  it("하이픈 없는 주민번호를 통째로 가린다", () => {
    expect(maskPii("0501013123456")).toBe("[주민번호]");
  });

  it("8자리 이상 숫자열은 일괄로 가린다", () => {
    expect(maskPii("계좌 12345678901")).toBe("계좌 [숫자]");
  });

  it("날짜·수식 숫자는 건드리지 않는다", () => {
    expect(maskPii("2026-11-13에 x=-b/2a, 3.14 계산")).toBe("2026-11-13에 x=-b/2a, 3.14 계산");
  });

  it("개인정보가 없으면 그대로 둔다", () => {
    expect(maskPii("이차함수 꼭짓점이 궁금해")).toBe("이차함수 꼭짓점이 궁금해");
  });
});
